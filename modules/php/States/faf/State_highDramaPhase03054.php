        protected Game $game,
    )
    {
        parent::__construct($game,
            id: States::HIGH_DRAMA_PLAYER_TURN_03054,
            type: StateType::ACTIVE_PLAYER,
            name: "highDramaPhase03054",

            description: clienttranslate('No Steel, No Surrender') . clienttranslate(': ${actplayer} must choose an opposing character to wound and move Home.'),
            descriptionMyTurn: clienttranslate('No Steel, No Surrender') . clienttranslate(': ${you} must choose an opposing character to wound and move Home:'),
            transitions: [
                "" => States::HIGH_DRAMA_PLAYER_TURN_EVENTS,
            ],
            updateGameProgression: false,
            initialPrivate: null,
        );
    }

    public function getArgs(): array
    {
        return $this->game->argsForState();
    }

    #[PossibleAction]
    public function actFromCardWithId(string $id): void
    {
        $this->game->actFromCardWithId($id);
    }

    public function zombie(int $playerId): void
    {
        $this->game->gamestate->nextState();
    }
}
